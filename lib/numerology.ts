export const SHULI: Shuli[] = ROWS.map(([level, title, gloss], index) => ({
  n: index + 1,
  level,
  title,
  gloss,
}))

export function shuliIndex(strokes: number): number {
  let value = Math.abs(strokes)
  if (value === 0) return 0
  while (value > 81) value -= 80
  return value
}

export function lookupShuli(strokes: number): Shuli {
  const index = shuliIndex(strokes)
  return SHULI[index - 1] ?? SHULI[0]
}

export function luckScore(level: Luck): number {
  return LEVEL_SCORE[level]
}

export function digitElement(strokes: number): "木" | "火" | "土" | "金" | "水" {
  const digit = Math.abs(strokes) % 10
  if (digit === 1 || digit === 2) return "木"
  if (digit === 3 || digit === 4) return "火"
  if (digit === 5 || digit === 6) return "土"
  if (digit === 7 || digit === 8) return "金"
  return "水"
}
